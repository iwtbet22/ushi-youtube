def ladder(hi=None, marker=None, side=None, w=900):
    """メジャーまでのはしご。hi 番目の段を金色に、marker 番目の段に「森井」の札。side = 段ごとの右側の文字"""
    rows = len(LEVELS)
    rh, gap = 112, 22
    h = rows * (rh + gap) + 40
    im = Image.new("RGBA", (w + 300, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    x0 = 20
    for i, name in enumerate(LEVELS):
        y = 20 + i * (rh + gap)
        on = i == hi
        col = GOLD if on else ((235, 230, 215) if i == 0 else (150, 150, 158))
        d.rounded_rectangle((x0, y, x0 + w, y + rh), radius=16, fill=(12, 12, 14, 215) if not on else (70, 52, 20, 235),
                            outline=col + (255,), width=5 if on or i == 0 else 3)
        d.text((x0 + 40, y + rh / 2), name, font=C.fit(name, 64, 330), fill=col, anchor="lm")
        if side:
            s = side[i]
            d.text((x0 + w - 36, y + rh / 2), s, font=C.fit(s, 46, w - 420, "NotoSansJP-Bold.ttf"), fill=C.INK,
                   anchor="rm")
        if i < rows - 1:
            d.line((x0 + 120, y + rh, x0 + 120, y + rh + gap), fill=(120, 110, 90, 255), width=6)
            d.line((x0 + w - 120, y + rh, x0 + w - 120, y + rh + gap), fill=(120, 110, 90, 255), width=6)
    if marker is not None:
        y = 20 + marker * (rh + gap) + rh / 2
        tag = "森井 ◀"
        d.rounded_rectangle((x0 + w + 24, y - 44, x0 + w + 280, y + 44), radius=14, fill=RED + (240,))
        d.text((x0 + w + 152, y), tag, font=C._f(50), fill=WHITE, anchor="mm")
    return im


def usmap(points=(), hi=None, w=1500, h=860, levels=True):
    """アメリカ本土の地図に、アスレチックスの傘下の町を置く"""
    lon0, lon1, lat0, lat1 = -126.0, -66.0, 24.0, 50.0
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)

    def xy(p):
        return ((p[0] - lon0) / (lon1 - lon0) * w, (lat1 - p[1]) / (lat1 - lat0) * h)

    d.polygon([xy(p) for p in US], fill=(62, 62, 68, 235), outline=(200, 200, 200, 255))
    f = C._f(52)
    fs = C._f(32, "NotoSansJP-Bold.ttf")
    for name in points:
        x, y = xy(CITY[name])
        col = RED if name == hi else GOLD
        r = 16 if name == hi else 12
        d.ellipse((x - r, y - r, x + r, y + r), fill=col + (255,), outline=(0, 0, 0, 255), width=3)
        lx, ly, anc = LABEL_AT[name]
        lx, ly = lx * w / 1500, ly * h / 860
        lab = name + (f"（{LEVEL_OF[name]}）" if levels else "")
        d.line((x, y, lx + (-8 if anc == "ra" else 8), ly + 26), fill=col + (200,), width=3)
        d.ellipse((x - r, y - r, x + r, y + r), fill=col + (255,), outline=(0, 0, 0, 255), width=3)
        d.text((lx, ly), lab, font=f, fill=(255, 255, 255, 255), stroke_width=5, stroke_fill=(0, 0, 0, 255),
               anchor=anc)
    d.text((w - 20, h - 16), "※位置はおおよそ", font=fs, fill=C.DIM, anchor="rd")
    return im


def roster(active=26, total=40, hi=None, labels=("26人（試合に出られる）", "40人枠")):
    """40人枠のうち26人が試合の枠、という点の図"""
    cols, cell = 10, 74
    rows = (total + cols - 1) // cols
    w, h = cols * cell + 40, rows * cell + 150
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rectangle((0, 0, w - 1, h - 1), fill=C.PANEL, outline=GOLD + (255,), width=3)
    for i in range(total):
        r, c = divmod(i, cols)
        cx, cy = 20 + c * cell + cell // 2, 20 + r * cell + cell // 2
        if i == hi:
            d.ellipse((cx - 28, cy - 28, cx + 28, cy + 28), fill=RED, outline=WHITE, width=4)
        elif i < active:
            d.ellipse((cx - 25, cy - 25, cx + 25, cy + 25), fill=GOLD)
        else:
            d.ellipse((cx - 25, cy - 25, cx + 25, cy + 25), outline=(220, 220, 220), width=4)
    f = C._f(40)
    y = 20 + rows * cell + 52
    d.ellipse((30, y - 18, 66, y + 18), fill=GOLD)
    if labels[0]:
        d.text((78, y), labels[0], font=C.fit(labels[0], 40, w * 0.5 - 100), fill=GOLD, anchor="lm")
    if labels[1]:
        d.ellipse((w * 0.5, y - 18, w * 0.5 + 36, y + 18), outline=(220, 220, 220), width=4)
        d.text((w * 0.5 + 48, y), labels[1], font=C.fit(labels[1], 40, w * 0.5 - 70), fill=C.INK, anchor="lm")
    return im


