def _shrink(fn, maxw):
    """画像が maxw より広ければ縮める"""
    from PIL import Image
    im = fn()
    if im.width <= maxw:
        return im
    return im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)


def _arrange(scenes):
    """人物の縦書きの名前と、ほかの文字がぶつからないように並べ直す。
    - 名前は左端の列 (x=150) に置き、紹介する文の間だけ出す (until を指定したものはそのまま)
    - 人物写真が右にある場面では、左側の文字を x=700 に寄せ、幅 820 以内に縮める (名前の列と写真の間に収める)"""
    for sc in scenes:
        bg = sc["bg"]
        right = getattr(bg, "keywords", {}).get("layout") == "right"
        for e in sc["els"]:
            fn = e["fn"]
            if getattr(fn, "func", None) is L.vertical:
                e["x"] = 150
                if e["until"] is None:
                    e["until"] = e["at"]
            elif right and e["x"] <= 760 and not e["dyn"]:
                e["x"] = 700
                e["fn"] = P(_shrink, fn, 820)
    return scenes


SCENES = _arrange(OPEN + BODY + ENDING)
