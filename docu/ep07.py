def logo_card(name):
    """ロゴを白い札にのせる (暗い背景でも読めるように)"""
    from PIL import Image, ImageDraw
    lg = Image.open(L.IMG / name).convert("RGBA")
    lg.thumbnail((1100, 300))
    w, h = lg.width + 160, lg.height + 140
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((0, 0, w - 1, h - 1), radius=28, fill=(250, 248, 242, 245))
    im.alpha_composite(lg, (80, 70))
    return im


def LOGO(name):
    return G((P(logo_card, name), 960, 360, 1300, 460))


def ATTB(n):
    return BARS([(t, v, i == 0) for i, (t, v) in enumerate(ATT[:n])], "人", 43000)


