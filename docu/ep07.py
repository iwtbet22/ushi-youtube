def _fix_speech(scenes):
    import readings
    for sc in scenes:
        out = []
        for line in sc["lines"]:
            text, sp = (line if isinstance(line, tuple) else (line, readings.speech(line)))
            for k, v in SPEECH_FIX.items():
                sp = sp.replace(k, v)
            sp = re.sub(r"(?<![0-9.,])0(?![0-9.,])", "ゼロ", sp)  # 0円 などは れい ではなく ゼロ と読ませる (確認済み)
