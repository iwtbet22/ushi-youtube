"""合成音声が読み間違える語の読み。

字幕は漢字のまま、音声だけ置き換えて読ませる (film.py の _speech が使う)。
新しい語を足すときは、先に tools/check_readings2.py で本当に読み間違えるかを確かめる。
"""
READ = {
    # tools/check_readings2.py で、漢字のままでは読み間違えると分かった語だけ。
    # 人名をひらがなにすると抑揚が平らになって不自然なので、置き換えは最小限にする。
    # 置き換えるときも、なるべく同じ読みの漢字やカタカナにして、自然な抑揚を保つ。
    "河野博文": "川野博文",          # こうの と読まれる
    "日本ハム": "ニッポンハム",        # にほんハム と読まれる
    "旧年俸": "前の年俸",            # きゅうねんぼう に近く読まれる
    "高木豊": "たかぎ豊",             # たかき と読まれやすい
    "蒲郡": "がまごおり",
    "炭谷銀仁朗": "すみたに銀仁朗",
    "いてまえ打線": "いてまえ だせん",
    "この間": "このあいだ",
}


def speech(text):
    for k in sorted(READ, key=len, reverse=True):
        text = text.replace(k, READ[k])
    return text
