"""合成音声が読み間違える語の読み。

字幕は漢字のまま、音声だけ置き換えて読ませる (film.py の _speech が使う)。
新しい語を足すときは、先に tools/check_readings2.py で本当に読み間違えるかを確かめる。
"""
READ = {
    # tools/check_readings2.py で、漢字のままでは読み間違えると分かった語だけ。
    # 人名をひらがなにすると抑揚が平らになって不自然なので、置き換えは最小限にする。
    # 置き換えるときも、なるべく同じ読みの漢字やカタカナにして、自然な抑揚を保つ。
    "河野博文": "川野博文",          # こうの と読まれる
    "日本ハム": "ニッポンハム",        # にほんハム と読まれる
    "旧年俸": "前の年俸",            # きゅうねんぼう に近く読まれる
    "蒲郡": "がまごおり",
    "炭谷銀仁朗": "すみたに銀仁朗",
    "いてまえ打線": "いてまえ だせん",
    "この間": "このあいだ",
    # ひらがなにしても漢字の読みに戻されることがある (あいだ→かん、としをこし→ねんをこし)。
    # そのときは置き換えではなく、台本の言い回しを変える。
    # 以下は tools/check_context.py (文の中での読み) で読み間違いと分かったもの
    "年をまたぐ": "としをまたぐ",      # ねんをまたぐ と読まれる
    "前の年の": "まえのとしの",
    "減った年に": "減ったとしに",
    "受けた年にも": "受けたとしにも",
    "自分で行って": "自分でおこなって",  # いって と読まれる
    "千賀投手": "せんが投手",          # ちが投手 と読まれる (千賀滉大 とフルネームなら正しい)
    # 以下は tools/check_yomi.py・check_kana.py で見つけ、tools/check_word.py の聞き比べで確かめたもの
    "関内": "かんない",              # 横浜関内 → よこはま せきうち と読まれた (セ・リーグ編で視聴者から指摘)
    "稼ぎ頭": "かせぎがしら",          # かせぎ かしら と読まれる
    "その間には": "そのあいだには",      # その かん には と読まれる
    "リーグの下には": "リーグのしたには",  # もと と読まれる
    "円の年が": "円のとしが",          # ねん と読まれる
}


# 数字のつく読みのうち、決まった形で読み間違えるもの (正規表現で直す)
PATTERNS = [
    # 10勝・20勝…90勝 (10勝目も) は「じゅう かち」と読まれる。11勝や57勝、100勝は正しく「しょう」。
    # 9本目「トレード事件簿」で 30勝・10勝 を「かち」と読み、視聴者から指摘された。
    (r"(?<![0-9０-９])([1-9]0)勝", r"\1しょう"),
]


def patterns(text):
    import re
    for pat, rep in PATTERNS:
        text = re.sub(pat, rep, text)
    return text


def speech(text):
    for k in sorted(READ, key=len, reverse=True):
        text = text.replace(k, READ[k])
    return patterns(text)
