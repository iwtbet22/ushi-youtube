def seg_years(rows, upto=None, w=1600, h=640):
    """日本とアジアのセグメント利益を、年ごとに並べる (赤字は下へ)。rows = [(年, 日本, アジア)] 単位は億円"""
    vmax = max(max(abs(a), abs(b)) for _, a, b in rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((0, 0, w - 1, h - 1), radius=12, fill=(6, 6, 8, 170))
    top, bot = 120, h - 90
    zero = top + (bot - top) * vmax / (2 * vmax)
    scale = (bot - top) / (2 * vmax)
    d.line((40, zero, w - 40, zero), fill=(200, 190, 170, 220), width=3)
    fl, fv = C._f(34, "NotoSansJP-Bold.ttf"), C._f(30, "NotoSansJP-Bold.ttf")
    d.rectangle((60, 34, 96, 70), fill=(150, 150, 158, 235))
    d.text((108, 52), "日本", font=C._f(36, "NotoSansJP-Bold.ttf"), fill=C.INK, anchor="lm")
    d.rectangle((240, 34, 276, 70), fill=GOLD + (235,))
    d.text((288, 52), "アジア", font=C._f(36, "NotoSansJP-Bold.ttf"), fill=C.INK, anchor="lm")
    d.text((w - 50, 52), "セグメント利益（億円）", font=C._f(30, "NotoSansJP-Bold.ttf"), fill=C.DIM, anchor="rm")
    n = len(rows)
    slot = (w - 120) / n
    bw = slot * 0.3
    for i, (yr, a, b) in enumerate(rows):
        if upto is not None and i > upto:
            break
        x0 = 60 + i * slot + slot * 0.18
        for j, (v, col) in enumerate([(a, (150, 150, 158) if a >= 0 else RED), (b, GOLD)]):
            x = x0 + j * (bw + 8)
            y = zero - v * scale
            d.rectangle((x, min(y, zero), x + bw, max(y, zero)), fill=col + (235,))
            s = f"{v:+.0f}".replace("+", "") if v >= 0 else f"△{-v:.0f}"
            d.text((x + bw / 2, y - 10 if v >= 0 else y + 10), s, font=fv, fill=col, anchor="ms" if v >= 0 else "mt")
        d.text((x0 + bw + 4, h - 40), yr, font=fl, fill=C.INK, anchor="mm")
    return im


