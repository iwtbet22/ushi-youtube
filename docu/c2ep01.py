def price_tag(old, new, label):
    """値札: 300円 → 320円"""
    a = L.text(old, "NotoSerifJP-Black.ttf", 110, (190, 185, 175))
    b = L.gold(new, size=150)
    arrow = L.text("→", "NotoSerifJP-Black.ttf", 110, GOLD)
    lab = L.text(label, "NotoSansJP-Bold.ttf", 56, WHITE)
    w = a.width + arrow.width + b.width + 80
    im = C.panel(max(w, lab.width + 80), max(a.height, b.height) + lab.height + 40)
    im.alpha_composite(lab, ((im.width - lab.width) // 2, 20))
    y = lab.height + 10
    x = (im.width - w) // 2 + 20
    for s in (a, arrow, b):
        im.alpha_composite(s, (x, y + (b.height - s.height) // 2))
        x += s.width + 20
    return im


def PRICE(old, new, label):
    return G((P(price_tag, old, new, label), 960, 340, 1400, 520))


