# ---- この回の図 ---------------------------------------------------------------
def swap(left, lp, right, rp, label=None, w=1600):
    """交換トレードの札。left/right = 球団名、lp/rp = 選手名のリスト"""
    n = max(len(lp), len(rp))
    ph = 150 + 78 * n
    im = Image.new("RGBA", (w, ph + 40), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    bw = (w - 220) // 2
    for i, (team, names) in enumerate(((left, lp), (right, rp))):
        x = i * (bw + 220)
        im.alpha_composite(C.panel(bw, ph), (x, 20))
        d.text((x + bw / 2, 85), team, font=C.fit(team, 58, bw - 60), fill=GOLD, anchor="mm")
        d.line((x + 40, 130, x + bw - 40, 130), fill=GOLD + (140,), width=2)
        for k, nm in enumerate(names):
            d.text((x + bw / 2, 180 + k * 78), nm, font=C.fit(nm, 52, bw - 60, "NotoSansJP-Bold.ttf"), fill=C.INK,
                   anchor="mm")
    cx = bw + 110
    d.text((cx, 20 + ph / 2 - 40), "⇔", font=C._f(110), fill=GOLD, anchor="mm")
    lab = label or f"{len(lp)}対{len(rp)}"
    d.text((cx, 20 + ph / 2 + 60), lab, font=C._f(54), fill=WHITE, anchor="mm")
    return im


def SWAP(left, lp, right, rp, label=None):
    return G((P(swap, left, lp, right, rp, label), 960, 380, 1650, 620))


