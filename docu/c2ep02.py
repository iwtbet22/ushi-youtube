SPEECH_FIX = {
    # 書き出しの前に tools/check_yomi.py・check_kana.py・check_word.py で確かめて足す
    "呪術廻戦": "じゅじゅつかいせん",  # 廻 を マワリ と読む (check_yomi)
    "空き部屋の割合": "あきべやの割合",  # アキヘヤ (check_yomi)
    "その間に、配信": "そのあいだに、配信",  # ソノカン (check_yomi)
}


def _fix_speech(scenes):
    import readings
    keys = sorted(SPEECH_FIX, key=len, reverse=True)
    for sc in scenes:
        out = []
        for line in sc["lines"]:
            text, sp = (line if isinstance(line, tuple) else (line, readings.speech(line)))
            for k in keys:
                sp = sp.replace(k, SPEECH_FIX[k])
            out.append((text, sp) if sp != text else text)
        sc["lines"] = out
    return scenes


