def _finish(scenes):
    """写真の説明を出し、写真の上の真ん中の文字を下3分の1へ下げ、文字の見た目をそろえる"""
    for sc in scenes:
        n = len(sc["lines"])
        marks = {0: sc["bg"], **dict(sc.get("bgs", []))}
        busy, cur = [], sc["bg"]
        for k in range(max(n, 1)):
            cur = marks.get(k, cur)
            busy.append(_busy(cur))
        for k, s in sc.pop("notes", []):
            bg = marks.get(k)
            if getattr(bg, "func", None) is not N.archive:
                continue  # 写真が取れていなければ説明も出さない
            until = next((j - 1 for j in sorted(marks) if j > k), None)
            sc["els"].append(E(P(C.note, s, 28), 960, 26, at=k, until=until, anchor="t", anim="fade"))
        for e in sc["els"]:
            ff = _restyle_text(e)
            if e["anchor"] == "c" and 360 <= e["y"] <= 480 and e["x"] == 960 and ff is not C.flow and n:
                lo = e["at"] or 0
                hi = e["until"] if e["until"] is not None else n - 1
                if any(busy[lo:hi + 1]):
                    e["y"] += 250
    return scenes


def _photos(fn, out):
    if isinstance(fn, str):
        if fn.lower().endswith((".jpg", ".jpeg", ".png")):
            out.append(fn)
    elif isinstance(fn, P):
        _photos(fn.func, out)
        for a in list(fn.args) + list(fn.keywords.values()):
            _photos(a, out)
    elif isinstance(fn, (list, tuple)):
        for a in fn:
            _photos(a, out)


def check_unique(scenes):
    """同じ写真が2つの場面で使われていないか (人物カードの顔写真は除く)"""
    seen = {}
    for i, sc in enumerate(scenes):
        names = []
        _photos(sc["bg"], names)
        for _, b in sc.get("bgs", []):
            _photos(b, names)
        for e in sc["els"]:
            _photos(e["fn"], names)
        for nm in set(names) - set(FACES.values()):
            assert nm not in seen, f"写真 {nm} が場面 {seen[nm]} と {i} で重複"
            seen[nm] = i
        for nm in set(names) & set(FACES.values()):
            if any(nm in str(b) for b in [sc["bg"]] + [b for _, b in sc.get("bgs", [])]):
                assert nm not in seen, f"写真 {nm} が背景として2度使われている"
                seen[nm] = i
    return seen


