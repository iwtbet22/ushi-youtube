def _fix_speech(scenes):
    import readings
    for sc in scenes:
        out = []
        for line in sc["lines"]:
            text, sp = (line if isinstance(line, tuple) else (line, readings.speech(line)))
            for k, v in SPEECH_FIX.items():
                sp = sp.replace(k, v)
            out.append((text, sp) if sp != text else text)
        sc["lines"] = out
    return scenes


def _finish(scenes):
    return ep05._finish(scenes)


def check_unique(scenes):
    """同じ写真が2つの場面で使われていないか (人物カードの顔写真は除く)"""
    seen = {}
    for i, sc in enumerate(scenes):
        names = []
        _photos(sc["bg"], names)
        for _, b in sc.get("bgs", []):
            _photos(b, names)
        for e in sc["els"]:
            _photos(e["fn"], names)
        for nm in set(names) - set(FACES.values()):
            assert nm not in seen, f"写真 {nm} が場面 {seen[nm]} と {i} で重複"
            seen[nm] = i
    return seen


