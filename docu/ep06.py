def donut(rows, center, sub=None, size=620, hi=None):
    """事業の内訳のドーナツ図。rows = [(名前, 値)]。hi 番目を金色で強調"""
    W_, H_ = size + 760, size + 40
    im = Image.new("RGBA", (W_, H_), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((0, 0, W_ - 1, H_ - 1), radius=18, fill=(6, 6, 8, 175))
    total = sum(v for _, v in rows)
    pal = [(150, 150, 158), (110, 120, 140), (130, 110, 100), (90, 110, 100), (120, 100, 130), (100, 100, 105)]
    box = (20, 20, 20 + size, 20 + size)
    a = -90.0
    fl = C._f(40, "NotoSansJP-Bold.ttf")
    fv = C._f(44)
    for i, (lab, v) in enumerate(rows):
        b = a + 360 * v / total
        col = GOLD if i == hi else pal[i % len(pal)]
        d.pieslice(box, a, b, fill=col + (255,), outline=(10, 10, 12, 255), width=6)
        a = b
        y = 70 + i * (size - 60) / max(1, len(rows) - 1) if len(rows) > 1 else size / 2
        d.rectangle((size + 70, y - 22, size + 110, y + 18), fill=col + (255,))
        d.text((size + 130, y), lab, font=C.fit(lab, 40, 400, "NotoSansJP-Bold.ttf"), fill=C.INK, anchor="lm")
        d.text((W_ - 30, y), f"{v:,.0f}億", font=fv, fill=col, anchor="rm")
    r = size * 0.30
    cx = cy = 20 + size / 2
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(12, 12, 14, 255))
    d.text((cx, cy - (24 if sub else 0)), center, font=C.fit(center, 64, r * 1.8), fill=GOLD, anchor="mm")
    if sub:
        d.text((cx, cy + 46), sub, font=C.fit(sub, 34, r * 1.7, "NotoSansJP-Bold.ttf"), fill=C.INK, anchor="mm")
    return im


def parent_card(name, rows, title="親会社"):
    """親会社の名刺: 名前と、いくつかの数字"""
    w = 1300
    h = 170 + 96 * len(rows)
    im = C.panel(w, h, width=4)
    d = ImageDraw.Draw(im)
    d.text((50, 40), title, font=C._f(40, "NotoSansJP-Bold.ttf"), fill=GOLD)
    d.text((50, 92), name, font=C.fit(name, 72, w - 100), fill=WHITE)
    fl, fv = C._f(46, "NotoSansJP-Bold.ttf"), C._f(56)
    for i, (a, b) in enumerate(rows):
        y = 200 + i * 96
        d.line((50, y - 18, w - 50, y - 18), fill=(120, 110, 90, 160), width=2)
        d.text((60, y + 26), a, font=fl, fill=C.INK, anchor="lm")
        d.text((w - 60, y + 26), b, font=C.fit(b, 56, w - 520), fill=GOLD, anchor="rm")
    return im


